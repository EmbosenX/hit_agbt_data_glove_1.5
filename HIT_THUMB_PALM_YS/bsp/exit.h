/**
 *******************************************************************************
 * @file        exit.h
 * @brief       PH0(CLK_SYNC) 外部触发同步信号驱动
 * @note        上升边沿触发外部中断，中断内通过 FreeRTOS 二值信号量通知任务
 ******************************************************************************/
#ifndef __EXIT_H__
#define __EXIT_H__

/*******************************************************************************
 * Include files
 ******************************************************************************/
#include "hc32_ll.h"
#include "FreeRTOS.h"
#include "semphr.h"

/*******************************************************************************
 * PH0 外部触发同步信号（CLK_SYNC）引脚配置
 ******************************************************************************/
#define EXIT_SYNC_PORT          (GPIO_PORT_H)       /* PH0 */
#define EXIT_SYNC_PIN           (GPIO_PIN_00)
#define EXIT_SYNC_EXTINT_CH     (EXTINT_CH00)       /* PH0 对应外部中断通道0 */
#define EXIT_SYNC_INT_SRC       (INT_SRC_PORT_EIRQ0)/* 外部中断0对应中断源 */
#define EXIT_SYNC_IRQn          (INT005_IRQn)       /* 映射到空闲 IRQ5 */
#define EXIT_SYNC_IRQ_PRIO      (DDL_IRQ_PRIO_06)   /* 中断优先级 */

/*******************************************************************************
 * 同步信号量句柄（PH0 上升沿触发时由 ISR 给出）
 ******************************************************************************/
extern SemaphoreHandle_t m_hSyncSem;

/*******************************************************************************
 * 返回值定义
 ******************************************************************************/
#define EXIT_OK                 (0U)    /* 成功 */
#define EXIT_ERR                (1U)    /* 失败 */
#define EXIT_ERR_TIMEOUT        (2U)    /* 等待超时 */

/*******************************************************************************
 * 对外接口
 ******************************************************************************/
/* 配置 PH0 上升沿外部中断（GPIO + EXTINT + INTC + NVIC） */
void    Exit_Sync_Config(void);
/* 创建同步二值信号量 */
uint8_t Exit_Sync_CreateSem(void);
/* 任务侧等待同步信号（阻塞，超时返回 EXIT_ERR_TIMEOUT） */
uint8_t Exit_Sync_Wait(uint32_t u32TimeoutMs);

#endif /* __EXIT_H__ */
